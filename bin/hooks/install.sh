#!/usr/bin/env bash
set -euo pipefail

# sudo-fleet/bin/hooks/install.sh — install the change-protocol git hooks.
#
# Copies the pre-commit enforcement hook into this repo's .git/hooks/ and makes
# it executable. Idempotent: safe to re-run. A foreign pre-commit hook (one not
# installed by us) is backed up and CHAINED to — never silently replaced.

HOOKS_SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"    # .../bin/hooks
REPO_ROOT="$(cd "$HOOKS_SRC/../.." && pwd)"                  # repo root

HOOKS_DEST="$(git -C "$REPO_ROOT" rev-parse --git-path hooks)"
case "$HOOKS_DEST" in
  /*) : ;;
  *)  HOOKS_DEST="$REPO_ROOT/$HOOKS_DEST" ;;
esac
mkdir -p "$HOOKS_DEST"

MARKER="sudo-fleet change-protocol hook (managed by bin/hooks/install.sh)"

for hook in pre-commit; do
  src="$HOOKS_SRC/$hook"
  dst="$HOOKS_DEST/$hook"
  orig="$dst.orig"

  # Back up a foreign hook exactly once; never overwrite an existing backup.
  if [ -e "$dst" ] && ! grep -qF "sudo-fleet change-protocol hook (managed" "$dst" 2>/dev/null; then
    if [ -e "$orig" ]; then
      mv "$dst" "$dst.foreign.$(date +%s)"
      echo "  foreign $hook present (and .orig already exists) -> $dst.foreign.$(date +%s)"
    else
      mv "$dst" "$orig"
      echo "  backed up foreign $hook -> $orig"
    fi
  fi

  # Install our wrapper (marked as ours). The wrapper runs the real hook, then
  # chains any backed-up foreign hook so its behaviour is preserved.
  cat > "$dst" <<EOF
#!/usr/bin/env bash
# $MARKER
# Wrapper generated by bin/hooks/install.sh — runs the real pre-commit hook,
# then chains any backed-up foreign hook so its behaviour is preserved.
set -u
repo_root="\$(git rev-parse --show-toplevel 2>/dev/null)" || repo_root="."
if [ -x "\$repo_root/bin/hooks/$hook" ]; then
  bash "\$repo_root/bin/hooks/$hook" || exit \$?
fi
if [ -x "$orig" ]; then
  "$orig" || exit \$?
fi
exit 0
EOF
  chmod +x "$dst"
  echo "  installed $dst"
done

echo "Done — change-protocol hook(s) installed in $HOOKS_DEST"
